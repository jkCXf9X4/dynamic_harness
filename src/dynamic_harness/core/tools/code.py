async def invoke(
    *, ctx: "ToolContext", code: str, timeout: int | None = None,
    workdir: str | None = None,
) -> str:
    """Execute a Python snippet with the ``harness_tools`` RPC bridge available.

    Trust parity with ``bash``: subprocess execution, process-group kill on
    timeout/cancel, cwd default = generated root, and a mutation heuristic for
    the repo lock. The snippet's harness-tool calls route through the runtime's
    ToolRegistry (policy parity by construction); only printed output enters
    context, terminal intent arrives via ``# TERMINAL:`` markers.
    """
    cfg: InvokeConfig = (ctx.config.invoke if ctx.config else None) or InvokeConfig()
    timeout_ms = int(timeout) if timeout is not None else cfg.timeout_ms

    code = code or ""
    if not code.strip():
        return "(no-op) empty code snippet"

    allowlist = list(cfg.import_allowlist or [])
    if allowlist:
        banned = _disallowed_imports(code, allowlist)
        if banned:
            return (
                "Error: invoke refused — the code imports modules outside the "
                f"configured import_allowlist: {', '.join(banned)}. Nothing was "
                "executed. Rewrite the snippet with only allowed imports or ask "
                "the operator to extend invoke.import_allowlist."
            )

    cwd = Path(workdir) if workdir else ctx.generated_root
    repo_lock = None
    if _looks_mutating(code):
        repo_lock = ctx.repo_lock()
        await repo_lock.acquire()

    result_ids: list[str] = []
    proc = None
    parent_sock, child_sock = socket.socketpair()
    parent_sock.setblocking(False)
    reader_task = asyncio.create_task(_serve_harness_tools(parent_sock, ctx, result_ids))
    try:
        with tempfile.TemporaryDirectory(prefix="harness_tools_") as td:
            stub_path = Path(td) / "harness_tools.py"
            stub_path.write_text(_STUB_SOURCE, encoding="utf-8")
            env = dict(os.environ)
            env["HARNESS_TOOLS"] = str(stub_path)
            env["HARNESS_TOOLS_FD"] = str(child_sock.fileno())
            env["PYTHONPATH"] = td + os.pathsep + env.get("PYTHONPATH", "")
            proc = await asyncio.create_subprocess_exec(
                "python3", "-u", "-",
                stdin=asyncio.subprocess.PIPE,
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.PIPE,
                cwd=cwd,
                start_new_session=True,
                pass_fds=(child_sock.fileno(),),
                env=env,
            )
            try:
                stdout, stderr = await asyncio.wait_for(
                    proc.communicate(code.encode()), timeout=timeout_ms / 1000
                )
            except asyncio.TimeoutError:
                await _kill_process_group(proc)
                return (
                    f"Error: invoke timed out after {timeout_ms}ms (the whole "
                    "process group was killed). Pass a larger 'timeout' (ms) "
                    "parameter, or narrow the snippet."
                )
            except asyncio.CancelledError:
                # Agent cancelled (kill/resume/reset) mid-snippet: take the
                # process group down before re-raising so no subprocess (or
                # spawned grandchild) is orphaned.
                await _kill_process_group(proc)
                raise
    finally:
        child_sock.close()
        parent_sock.close()
        reader_task.cancel()
        if repo_lock:
            repo_lock.release()

    out_text = stdout.decode(errors="replace") if stdout else ""
    err_text = stderr.decode(errors="replace") if stderr else ""
    out_text = _cap_text(out_text, cfg.stdout_cap, "stdout") if cfg.stdout_cap else out_text
    err_text = _cap_text(err_text, cfg.stderr_cap, "stderr") if cfg.stderr_cap else err_text

    result = out_text
    if err_text:
        result += f"\n(STDERR)\n{err_text}"
    result, _ = _handle_terminal_markers(result, ctx)
    if result_ids:
        # Dedupe while preserving order: the same snapshot may be referenced by
        # several bridge calls (e.g. read twice served from one snapshot).
        seen: set[str] = set()
        ids = [rid for rid in result_ids if not (rid in seen or seen.add(rid))]
        result += "\n# result: " + " ".join(ids)
    return result.strip() or "(no output)"