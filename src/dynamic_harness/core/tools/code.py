#: Tools the sandbox may not reach through the bridge: recursive invoke,
#: bash/result paging (agent-level execution), and the terminal tools (their
#: intent is expressed via printed markers instead).
_BLOCKED_RPC_TOOLS: frozenset[str] = frozenset({
    "invoke", "bash", "result_read", "result_bash",
    "report", "escalate", "fail",
})

_BLOCKED_RPC_MESSAGE = (
    "Error: tool '{name}' is not available inside invoke — the terminal "
    "tools (report/escalate/fail) are expressed by printing the # TERMINAL: "
    "marker (harness_tools.report/...), and invoke/bash/result paging are "
    "agent-level tools."
)

_TERMINAL_RE = re.compile(r"^# TERMINAL:(report|escalate|fail):(.*)$", re.MULTILINE)


async def _serve_harness_tools(
    sock: socket.socket, ctx: "ToolContext", result_ids: list[str]
) -> None:
    """Service JSON-lines requests from a sandboxed ``invoke`` subprocess.

    Each request is forwarded through ``ToolRegistry.execute()`` so the exact
    policies that govern the direct tools (role allow-list, sandbox roots,
    spawn caps, comms routing, budget lines) apply to the code-driven call.
    Runs as a task alongside ``proc.communicate``; exits on socket EOF.
    """
    reader, writer = await asyncio.open_connection(sock=sock)
    try:
        while True:
            line = await reader.readline()
            if not line:
                break
            try:
                req = json.loads(line)
            except json.JSONDecodeError:
                continue
            rid = req.get("id", 0)
            name = str(req.get("name", ""))
            args = dict(req.get("arguments") or {})
            result_id = None
            if name in _BLOCKED_RPC_TOOLS:
                content = _BLOCKED_RPC_MESSAGE.format(name=name)
            else:
                try:
                    # token_limit huge: the CODE needs the full payload in-process
                    # (lean-context is achieved by the invoke footer + what the
                    # snippet prints, not by slicing the bridge's answers).
                    # Strip any pagination knobs the stub mirrored from the tool
                    # signature so they cannot collide with the outer override.
                    args.pop("token_limit", None)
                    args.pop("token_offset", None)
                    result = await ctx.tool_registry.execute(
                        name, f"invoke-{rid}", agent=ctx,
                        token_limit=10**6, **args,
                    )
                    content = result.content or ""
                    result_id = getattr(result, "result_id", None)
                    if result_id:
                        result_ids.append(result_id)
                except Exception as exc:  # noqa: BLE001
                    content = f"Error executing {name}: {exc}"
            writer.write(
                json.dumps({"id": rid, "content": content, "result_id": result_id}).encode()
                + b"\n"
            )
            await writer.drain()
    finally:
        writer.close()
        try:
            await writer.wait_closed()
        except Exception:  # noqa: BLE001
            pass


def _handle_terminal_markers(text: str, ctx: "ToolContext") -> tuple[str, bool]:
    """Scan ``invoke`` output for ``# TERMINAL:<name>:<json>`` markers and
    deliver the FIRST one through the agent's terminal path.

    The marker line is replaced with a ``[terminal: ...]`` note so the model's
    context stays clean. Returns ``(text, delivered)``.
    """
    m = _TERMINAL_RE.search(text)
    if not m:
        return text, False
    name, raw = m.group(1), m.group(2)
    try:
        payload = json.loads(raw)
    except json.JSONDecodeError:
        return text, False
    note = {
        "report": "[terminal: report delivered]",
        "escalate": "[terminal: escalated]",
        "fail": "[terminal: failed]",
    }[name]
    text = text[: m.start()] + note + text[m.end():]
    try:
        if name == "report":
            ctx.report(ReportPayload(
                task_id=ctx.task_id,
                summary=str(payload.get("summary", "")),
                technical_summary=payload.get("technical_summary"),
                full_report=payload.get("full_report"),
                confidence=payload.get("confidence"),
                artifact_ids=list(payload.get("artifact_ids") or []),
                files_written=list(payload.get("files_written") or []),
            ))
        elif name == "escalate":
            ctx.escalate(
                str(payload.get("issue", "")),
                **{k: v for k, v in payload.items() if k != "issue"},
            )
        else:
            ctx.fail(str(payload.get("error", "")), trace=payload.get("trace"))
    except Exception:  # noqa: BLE001 — never crash the tool over a bad payload
        return text, False
    return text, True


# ---------------------------------------------------------------------------
# Import allowlist (v1 discipline knob; default off = parity with bash)
# ---------------------------------------------------------------------------

_IMPORT_RE = re.compile(
    r"^\s*(?:import|from)\s+([A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*)",
    re.MULTILINE,
)


def _disallowed_imports(code: str, allowlist: list[str]) -> list[str]:
    """Top-level modules imported by ``code`` that are not in ``allowlist``."""
    allowed = {m.split(".")[0] for m in allowlist}
    seen: set[str] = set()
    banned: list[str] = []
    for match in _IMPORT_RE.finditer(code or ""):
        root = match.group(1).split(".")[0]
        if root in seen or root in allowed:
            continue
        seen.add(root)
        banned.append(root)
    return sorted(banned)


#: Heuristic mutation detection for the repo lock (mirrors bash's read-only
#: classification in spirit: a clearly read/compute-only snippet skips the
#: lock; anything that plausibly writes takes it). Conservative — false
#: positives only cost a short serialization, never a corrupted workspace.
_MUTATION_RE = re.compile(
    r"\.write_text\(|\.write_bytes\(|\.open\(|open\(|"
    r"os\.(?:remove|unlink|rename|rmdir|makedirs|mkdir|symlink|replace|system|popen)|"
    r"shutil\.|subprocess|\.mkdir\(|\.rmdir\(|\.unlink\(|\.touch\(|"
    r"\.move\(|\.copy\(|\.rename\(|Path\([^)]*\)\.write"
)


def _looks_mutating(code: str) -> bool:
    return bool(_MUTATION_RE.search(code or ""))


def _cap_text(text: str, cap: int, label: str) -> str:
    """Slice ``text`` to ``cap`` bytes with a truncation note (v1 config knob;
    default None = uncapped, parity with bash: full output is retained and
    paged via result_read)."""
    if len(text) <= cap:
        return text
    return (
        text[:cap]
        + f"\n[{label} truncated at {cap} bytes — bytes beyond are NOT retained; "
        "re-run invoke with a narrower scope to see more]"
    )


