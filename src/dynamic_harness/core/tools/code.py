"""Code-as-action: the ``invoke`` tool (v1 probe surface).

Mirrors ``process.py:bash`` for the execution machinery — same subprocess
pattern, process-group kill, ``CancelledError`` handling, and repo-lock
heuristic — so v1 holds *trust parity with bash* (the harness's existing
deliberate security-boundary decision; hard sandboxing is a later, config-gated
hardening per the code-as-action investigation, proposal §1/§4).

Difference from ``bash``: the action is a Python snippet, and the snippet runs
with a generated ``harness_tools`` RPC bridge on a private socket. Every
harness-tool call the code makes (``read``/``grep``/``delegate``/``ask``/
``converse``/``post``/...) is executed by the parent through
``ToolRegistry.execute()`` — **policy parity by construction** (sandbox roots,
role allow-lists, spawn caps, comms routing, budget lines all apply). Only
what the snippet prints (plus a ``# result:`` footer listing snapshot handles)
enters the agent's context; tool payloads stay in-process and are snapshotted
so the model can page them via ``result_read``.

Terminal intent from inside the sandbox is expressed by *printing a marker*
(``# TERMINAL:report:...``), which the harness loop recognizes and delivers —
the terminal contract stays enforced, and the sandboxed code never invokes the
terminal tools directly.
"""

